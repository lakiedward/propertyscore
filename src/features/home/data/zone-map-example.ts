const ZONE_CATEGORIES = [
  'education',
  'transport',
  'green',
  'health',
  'shopping',
  'safety',
] as const;
export type ZoneCategory = (typeof ZONE_CATEGORIES)[number];

function isZoneCategory(value: string): value is ZoneCategory {
  return ZONE_CATEGORIES.some((category) => category === value);
}

